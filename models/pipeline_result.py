"""
models/pipeline_result.py
=========================
Type-safe result structure returned by main.py::run_pipeline()
and consumed by orchestrators such as run_pipeline.py.
Integrates with the canonical LeadRecord contract.
"""

from dataclasses import dataclass, field
from typing import List, Dict, Any, Optional, Iterator, Union, TYPE_CHECKING

if TYPE_CHECKING:
    from models.lead_record import LeadRecord


@dataclass
class PipelineResult:
    """
    Structured outcome of a pipeline execution.

    Attributes
    ----------
    records : List[Union[Dict[str, Any], LeadRecord]]
        The list of lead dictionaries or LeadRecords generated by the pipeline.
    raw_file : Optional[str]
        Absolute or relative filesystem path to the raw output JSON file.
    record_count : int
        Number of valid leads produced.
    status : str
        Status string: 'success', 'partial', 'no_candidates', 'exhausted', 'error'.
    error_message : Optional[str]
        Optional details if execution was aborted or encountered an error.
    """
    records: List[Union[Dict[str, Any], Any]] = field(default_factory=list)
    raw_file: Optional[str] = None
    record_count: int = 0
    status: str = "success"
    error_message: Optional[str] = None

    @property
    def lead_records(self) -> List["LeadRecord"]:
        """Return leads lazily parsed into canonical LeadRecord instances."""
        from models.lead_record import LeadRecord
        parsed = []
        for r in self.records:
            if isinstance(r, LeadRecord):
                parsed.append(r)
            elif isinstance(r, dict):
                parsed.append(LeadRecord.from_dict(r))
        return parsed

    def __bool__(self) -> bool:
        """Truthiness check reflects whether the pipeline produced an output file or records."""
        return bool(self.raw_file or self.records)

    def __iter__(self) -> Iterator[Any]:
        """Allow iteration over records for backward compatibility."""
        return iter(self.records)

    def __len__(self) -> int:
        """Allow len() check on the result for backward compatibility."""
        return self.record_count

    def __getitem__(self, index: int) -> Any:
        """Allow indexing for backward compatibility."""
        return self.records[index]
